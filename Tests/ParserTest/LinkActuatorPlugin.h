#pragma once

#include <actuators/LinkActuator.h>

namespace sf
{
    //! A class representing an example of an actuator plugin that can be attached to a link.
    class LinkActuatorPlugin : public LinkActuator
    {
    public:
        //! A constructor.
        /*!
         \param uniqueName a name for the actuator
         \param amplitude the amplitude of the sine wave signal generated by the actuator [1]
         \param frequency the frequency of the sine wave signal generated by the actuator [Hz]
         */
        LinkActuatorPlugin(std::string_view uniqueName, Scalar amplitude, Scalar frequency);

        //! A method used to update the internal state of the actuator.
        /*!
         \param dt a time step of the simulation [s]
         */
        void Update(Scalar dt) override;

        //! A method returning the type of link actuator.
        LinkActuatorType GetLinkActuatorType() const override;

        //! A method returning the construction info for the actuator.
        static ConstructInfo GetConstructInfo();

        //! A method constructing the actuator based on info structure.
        /*!  
         \param uniqueName a name for the actuator
         \param info a structure containing construction information
         */
        static LinkActuatorPlugin* Construct(std::string_view uniqueName, ConstructInfo* info);
    private:
        Scalar amplitude_;
        Scalar frequency_;
        Scalar time_;
    };
}
